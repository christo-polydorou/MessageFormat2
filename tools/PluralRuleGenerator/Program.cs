using System.Text;
using System.Text.Json;

using PluralRuleGenerator;

// Reads the CLDR plural rules and writes them as C#. Run from the repository root.
string dataDirectory = args.Length > 0 ? args[0] : "tools/PluralRuleGenerator/cldr";
string outputPath = args.Length > 1 ? args[1] : "src/MessageFormat2/Plurals/PluralRules.g.cs";

string[] categoryOrder = ["zero", "one", "two", "few", "many", "other"];

var output = new StringBuilder();
output.AppendLine("// <auto-generated>");
output.AppendLine("// Generated by tools/PluralRuleGenerator from CLDR plural rules. Do not edit by hand.");
output.AppendLine("// </auto-generated>");
output.AppendLine();
output.AppendLine("namespace MessageFormat2.Plurals;");
output.AppendLine();
output.AppendLine("internal static partial class PluralRules");
output.AppendLine("{");

string version = "";
foreach ((string file, string type, string name) in new[]
{
    ("plurals.json", "plurals-type-cardinal", "Cardinal"),
    ("ordinals.json", "plurals-type-ordinal", "Ordinal"),
})
{
    using JsonDocument document = JsonDocument.Parse(File.ReadAllText(Path.Combine(dataDirectory, file)));
    JsonElement supplemental = document.RootElement.GetProperty("supplemental");
    version = supplemental.GetProperty("version").GetProperty("_cldrVersion").GetString()!;

    // Many languages share the same rules, so each distinct rule set becomes one method.
    var methodsByBody = new Dictionary<string, string>(StringComparer.Ordinal);
    var languagesByMethod = new SortedDictionary<string, List<string>>(StringComparer.Ordinal);

    foreach (JsonProperty language in supplemental.GetProperty(type).EnumerateObject().OrderBy(p => p.Name, StringComparer.Ordinal))
    {
        var rules = language.Value.EnumerateObject().ToDictionary(
            rule => rule.Name["pluralRule-count-".Length..],
            rule => rule.Value.GetString()!);

        var body = new StringBuilder();
        foreach (string category in categoryOrder.Where(c => c != "other" && rules.ContainsKey(c)))
        {
            body.AppendLine($"        if ({RuleTranslator.Translate(rules[category])})");
            body.AppendLine("        {");
            body.AppendLine($"            return PluralCategory.{char.ToUpperInvariant(category[0])}{category[1..]};");
            body.AppendLine("        }");
            body.AppendLine();
        }

        body.AppendLine("        return PluralCategory.Other;");

        string key = body.ToString();
        if (!methodsByBody.TryGetValue(key, out string? method))
        {
            method = $"{name}{methodsByBody.Count}";
            methodsByBody.Add(key, method);
            languagesByMethod[method] = [];
        }

        languagesByMethod[method].Add(language.Name);
    }

    output.AppendLine($"    /// <summary>The {name.ToLowerInvariant()} plural category, or null if CLDR has no {name.ToLowerInvariant()} rules for the language.</summary>");
    output.AppendLine($"    /// <param name=\"language\">A CLDR language identifier, such as <c>en</c> or <c>pt-PT</c>.</param>");
    output.AppendLine($"    /// <param name=\"o\">The plural operands of the formatted number.</param>");
    output.AppendLine($"    public static PluralCategory? {name}(string language, in PluralOperands o) => language switch");
    output.AppendLine("    {");
    foreach ((string method, List<string> languages) in languagesByMethod.OrderBy(entry => int.Parse(entry.Key[name.Length..])))
    {
        output.AppendLine($"        {string.Join(" or ", languages.Select(l => $"\"{l}\""))} => {method}(o),");
    }

    output.AppendLine("        _ => null,");
    output.AppendLine("    };");
    output.AppendLine();

    foreach ((string body, string method) in methodsByBody.OrderBy(entry => int.Parse(entry.Value[name.Length..])))
    {
        output.AppendLine($"    private static PluralCategory {method}(in PluralOperands o)");
        output.AppendLine("    {");
        output.Append(body);
        output.AppendLine("    }");
        output.AppendLine();
    }
}

output.AppendLine($"    /// <summary>The CLDR version the rules were generated from.</summary>");
output.AppendLine($"    public const string CldrVersion = \"{version}\";");
output.AppendLine("}");

Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
File.WriteAllText(outputPath, output.ToString().Replace("\r\n", "\n", StringComparison.Ordinal));
Console.WriteLine($"Wrote {outputPath} (CLDR {version}).");
